fn base_stops(name: &str) -> &'static [[u8; 3]] {
    for (key, stops) in TABLES {
        if *key == name {
            return stops;
        }
    }
    VIRIDIS
}

/// Resolve a built-in colormap name, including `_r` reversal.
/// Unknown names fall back to viridis, matching the retired host tables.
pub fn colormap_named_stops(name: &str) -> Vec<[u8; 3]> {
    let reversed = name.ends_with("_r");
    let base = if reversed && name.len() >= 2 {
        &name[..name.len() - 2]
    } else {
        name
    };
    let stops = base_stops(base);
    if reversed {
        stops.iter().copied().rev().collect()
    } else {
        stops.to_vec()
    }
}

/// Write packed RGB triples into `out`. Returns the stop count, or 0 if
/// `out` is too small.
pub fn write_colormap_stops(name: &str, out: &mut [u8]) -> usize {
    let stops = colormap_named_stops(name);
    let needed = stops.len().saturating_mul(COLORMAP_STOP_BYTES);
    if out.len() < needed {
        return 0;
    }
    for (index, stop) in stops.iter().enumerate() {
        let start = index * COLORMAP_STOP_BYTES;
        out[start..start + 3].copy_from_slice(stop);
    }
    stops.len()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_names_fall_back_to_viridis() {
        assert_eq!(colormap_named_stops("nope"), VIRIDIS);
        assert_eq!(colormap_named_stops("nope_r"), colormap_named_stops("viridis_r"));
    }

    #[test]
    fn reverse_suffix_reverses_stops() {
        let forward = colormap_named_stops("plasma");
        let reverse = colormap_named_stops("plasma_r");
        assert_eq!(reverse, forward.into_iter().rev().collect::<Vec<_>>());
    }

    #[test]
    fn flag_has_native_lut_resolution() {
        assert_eq!(colormap_named_stops("flag").len(), 256);
    }
}
