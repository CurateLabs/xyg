"""Native Python half of the #1007 browser-painter admission parity contract.

``tests/fixtures/painter_admission_cross_host.json`` is generated by
``crates/xyg-wasm/tests/painter_admission_parity.rs``, which already proves the
native C seam and the WASM Worker ABI agree. Python rebuilds each compact recipe
through the Rust-backed ``scene_batch_encode``, proves byte identity with
``scene_sha256``, and must observe the same painter bytes or the same stable
``scene::PainterRejection`` diagnostic through ``_native.scene_browser_painter``.
"""

from __future__ import annotations

import hashlib
import json
import struct
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from xyg import _native

FIXTURE = json.loads(
    (Path(__file__).parent / "fixtures" / "painter_admission_cross_host.json").read_text()
)
CASES = {case["name"]: case for case in FIXTURE["cases"]}


def _scene(case: dict[str, Any]) -> bytes:
    recipe = FIXTURE["recipe"]
    n = case["count"]
    style = recipe["style"]
    scene = _native.scene_batch_encode(
        viewport=tuple(recipe["viewport"]),
        margins=tuple(recipe["margins"]),
        x_axis=(recipe["x_axis"]["id"], 0, *recipe["x_axis"]["domain"], 1.0, False),
        y_axis=(recipe["y_axis"]["id"], 0, *recipe["y_axis"]["domain"], 1.0, False),
        kinds=np.full(n, case["kind"], dtype=np.uint8),
        stable_ids=(
            np.arange(n, dtype=np.uint64) if case["distinct_ids"] else np.full(n, 7, np.uint64)
        ),
        style_refs=np.full(n, recipe["style_ref"], dtype=np.uint32),
        fill_rgba=style["fill_rgba"],
        stroke_rgba=style["stroke_rgba"],
        stroke_width=[float(style["stroke_width"])],
        diameter=np.full(n, case["diameter"]),
        symbols=(
            (np.arange(n) % 2).astype(np.uint8)
            if case["alternate_symbols"]
            else np.zeros(n, np.uint8)
        ),
        x0=np.full(n, recipe["x0"], dtype=np.float64),
        y0=np.full(n, recipe["y0"], dtype=np.float64),
        x1=np.full(n, float(recipe["x1"])),
        y1=np.full(n, float(recipe["y1"])),
    )
    if case["mutation"] == "truncate_last_byte":
        scene = scene[:-1]
    elif case["mutation"] == "next_scene_version":
        scene = scene[:4] + struct.pack("<I", FIXTURE["scene_version"] + 1) + scene[8:]
    else:
        assert case["mutation"] == "none"
    return scene


def test_fixture_covers_every_admission_boundary() -> None:
    assert FIXTURE["schema"] == "xyg.painter-admission-cross-host/v1"
    assert FIXTURE["max_traces"] == 1024
    limit = FIXTURE["max_traces"]
    assert CASES["trace_runs_just_below"]["traces"] == limit - 1
    assert CASES["trace_runs_exact"]["traces"] == limit
    assert CASES["trace_runs_just_above"]["count"] == limit + 1
    assert CASES["trace_runs_just_above"]["code"] == "XYG_PAINTER_TRACE_LIMIT"
    # Run discovery precedes byte admission: the trace code wins under a
    # budget that could never hold the output.
    assert CASES["trace_runs_above_with_scene_sized_budget"]["code"] == "XYG_PAINTER_TRACE_LIMIT"
    assert CASES["trace_runs_exact_with_scene_sized_budget"]["code"] == "XYG_PAINTER_BYTE_LIMIT"
    assert CASES["packed_symbols_above_trace_count"]["traces"] == 1
    exact = CASES["bytes_exact"]["painter_bytes"]
    assert CASES["bytes_just_below"]["max_bytes"] == exact - 1
    assert CASES["bytes_exact"]["max_bytes"] == exact
    assert CASES["bytes_just_above"]["max_bytes"] == exact + 1
    assert {case.get("code") for case in FIXTURE["cases"]} >= {
        "XYG_PAINTER_TRACE_LIMIT",
        "XYG_PAINTER_BYTE_LIMIT",
        "XYG_SCENE_MALFORMED",
        "XYG_SCENE_VERSION",
    }


@pytest.mark.parametrize("name", sorted(CASES))
def test_native_python_matches_rust_admission_outcome(name: str) -> None:
    case = CASES[name]
    scene = _scene(case)
    assert len(scene) == case["scene_bytes"]
    assert hashlib.sha256(scene).hexdigest() == case["scene_sha256"]
    if case["outcome"] == "ok":
        painter = _native.scene_browser_painter(scene, case["max_bytes"])
        assert len(painter) == case["painter_bytes"]
        assert hashlib.sha256(painter).hexdigest() == case["painter_sha256"]
        assert struct.unpack_from("<I", painter, 20)[0] == case["traces"]
        return
    with pytest.raises(_native.ScenePainterError) as raised:
        _native.scene_browser_painter(scene, case["max_bytes"])
    assert raised.value.code == case["code"]
    assert str(raised.value) == case["diagnostic"]
    # The bounded-resource diagnostic is still a ValueError for older callers.
    assert isinstance(raised.value, ValueError)


def test_rejection_then_retry_is_stateless_and_byte_identical() -> None:
    above = _scene(CASES["trace_runs_just_above"])
    exact = CASES["trace_runs_exact"]
    scene = _scene(exact)
    first = _native.scene_browser_painter(scene, exact["max_bytes"])
    with pytest.raises(_native.ScenePainterError, match=r"^XYG_PAINTER_TRACE_LIMIT: "):
        _native.scene_browser_painter(above, exact["max_bytes"])
    with pytest.raises(_native.ScenePainterError, match=r"^XYG_PAINTER_BYTE_LIMIT: "):
        _native.scene_browser_painter(scene, len(first) - 1)
    assert _native.scene_browser_painter(scene, len(first)) == first
